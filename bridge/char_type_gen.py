#!/usr/bin/env python3
"""Generate bridge/char_type_ranges.inc for GetStringTypeW/A.

The table maps Unicode code point ranges to the Windows character-type classes
(CT_CTYPE1 / CT_CTYPE2 / CT_CTYPE3). The classes are derived from the Unicode
character database (Python's unicodedata, following the same UnicodeData.txt
categories Windows is built from), with the documented Windows additions such
as the fullwidth hexadecimal digits and the C1_BLANK set.

Usage: python3 bridge/char_type_gen.py > bridge/char_type_ranges.inc
"""

import sys
import unicodedata as ud

C1_UPPER, C1_LOWER, C1_DIGIT, C1_SPACE = 0x0001, 0x0002, 0x0004, 0x0008
C1_PUNCT, C1_CNTRL, C1_BLANK, C1_XDIGIT = 0x0010, 0x0020, 0x0040, 0x0080
C1_ALPHA, C1_DEFINED = 0x0100, 0x0200

C2 = {
    'L': 0x0001, 'R': 0x0002, 'AL': 0x0002, 'EN': 0x0003, 'ES': 0x0004,
    'ET': 0x0005, 'AN': 0x0006, 'CS': 0x0007, 'B': 0x0008, 'S': 0x0009,
    'WS': 0x000A, 'ON': 0x000B, 'BN': 0x000B, 'NSM': 0x000B,
}

C3_NONSPACING, C3_DIACRITIC, C3_VOWELMARK, C3_SYMBOL = 0x0001, 0x0002, 0x0004, 0x0008
C3_KATAKANA, C3_HIRAGANA, C3_HALFWIDTH, C3_FULLWIDTH = 0x0010, 0x0020, 0x0040, 0x0080
C3_IDEOGRAPH, C3_KASHIDA, C3_LEXICAL = 0x0100, 0x0200, 0x0400
C3_HIGHSURROGATE, C3_LOWSURROGATE, C3_ALPHA = 0x0800, 0x1000, 0x8000

BLANK_CONTROLS = (0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x85)
XDIGIT_FULLWIDTH = list(range(0xFF10, 0xFF1A)) + list(range(0xFF21, 0xFF27)) + \
                   list(range(0xFF41, 0xFF47))
XDIGIT_FULLWIDTH = set(XDIGIT_FULLWIDTH)


def name_of(cp):
    try:
        return ud.name(chr(cp))
    except ValueError:
        return ''


def ctype1(cp, cat):
    value = 0
    if cat != 'Cn':
        value |= C1_DEFINED
    if cat in ('Lu', 'Lt'):
        value |= C1_UPPER | C1_ALPHA
    elif cat == 'Ll':
        value |= C1_LOWER | C1_ALPHA
    elif cat in ('Lm', 'Lo', 'Nl'):
        value |= C1_ALPHA
    if cat == 'Nd':
        value |= C1_DIGIT
    if cat in ('Zs', 'Zl', 'Zp'):
        value |= C1_SPACE | C1_BLANK
    if cp in BLANK_CONTROLS:
        value |= C1_SPACE | C1_BLANK
    if cat.startswith('P'):
        value |= C1_PUNCT
    if cat in ('Cc', 'Cf'):
        value |= C1_CNTRL
    if cp < 128 and chr(cp) in '0123456789abcdefABCDEF':
        value |= C1_XDIGIT
    elif cp in XDIGIT_FULLWIDTH:
        value |= C1_XDIGIT
    return value


def ctype2(cp, cat):
    if cat in ('Cc', 'Cf', 'Cn', 'Cs'):
        return 0x0000                     # C2_NOTAPPLICABLE: no implicit directionality
    return C2.get(ud.bidirectional(chr(cp)), 0x000B)


def ctype3(cp, cat):
    value = 0
    if 0xD800 <= cp <= 0xDBFF:
        value |= C3_HIGHSURROGATE
    if 0xDC00 <= cp <= 0xDFFF:
        value |= C3_LOWSURROGATE
    if cat == 'Mn':
        value |= C3_NONSPACING
        if ud.combining(chr(cp)):
            value |= C3_DIACRITIC
    if cat.startswith('S'):
        value |= C3_SYMBOL
    if cat[0] == 'L':
        value |= C3_LEXICAL | C3_ALPHA
    name = name_of(cp)
    if 'KATAKANA' in name:
        value |= C3_KATAKANA
    if 'HIRAGANA' in name:
        value |= C3_HIRAGANA
    if 'IDEOGRAPH' in name:
        value |= C3_IDEOGRAPH
    if 'FULLWIDTH' in name:
        value |= C3_FULLWIDTH
    if 'HALFWIDTH' in name:
        value |= C3_HALFWIDTH
    if 'VOWEL' in name:
        value |= C3_VOWELMARK
    if cp == 0x0640:
        value |= C3_KASHIDA
    return value


def case_deltas(cp):
    """Simple (one code point to one code point) lower/upper deltas.

    Expanding mappings such as U+00DF -> "SS" are left unchanged, matching the
    one-character mapping LCMapString performs."""
    ch = chr(cp)
    lower = ch.lower()
    upper = ch.upper()
    return (ord(lower) - cp if len(lower) == 1 else 0,
            ord(upper) - cp if len(upper) == 1 else 0)


def case_ranges(limit=0x110000):
    current = None
    for cp in range(limit):
        deltas = case_deltas(cp)
        if current and current[2] == deltas:
            current = (current[0], cp, deltas)
            continue
        if current:
            yield current
        current = (cp, cp, deltas)
    if current:
        yield current


def ranges(limit=0x110000):
    current = None
    for cp in range(limit):
        cat = ud.category(chr(cp))
        row = (ctype1(cp, cat), ctype2(cp, cat), ctype3(cp, cat))
        if current and current[2] == row:
            current = (current[0], cp, row)
            continue
        if current:
            yield current
        current = (cp, cp, row)
    if current:
        yield current


def main():
    out = sys.stdout
    version = ud.unidata_version
    out.write('/* Generated by bridge/char_type_gen.py from the Unicode %s character\n'
              ' * database. Do not edit by hand: regenerate with\n'
              ' *   python3 bridge/char_type_gen.py > bridge/char_type_ranges.inc\n'
              ' * Code points are merged into runs that share all three CT_* classes. */\n'
              % version)
    out.write('struct pe_char_type_range {\n'
              '    uint32_t first, last, ctype1;\n'
              '    uint16_t ctype3;\n'
              '    uint8_t ctype2, pad;\n'
              '};\n')
    rows = list(ranges())
    out.write('static const struct pe_char_type_range pe_char_type_ranges[] = {\n')
    for first, last, row in rows:
        out.write('    { 0x%05x, 0x%05x, 0x%04x, 0x%04x, 0x%02x, 0 },\n'
                  % (first, last, row[0], row[2], row[1]))
    out.write('};\n')
    cases = list(case_ranges())
    out.write('struct pe_case_range {\n'
              '    uint32_t first, last;\n'
              '    int32_t lower_delta, upper_delta;\n'
              '};\n')
    out.write('static const struct pe_case_range pe_case_ranges[] = {\n')
    for first, last, deltas in cases:
        out.write('    { 0x%05x, 0x%05x, %d, %d },\n'
                  % (first, last, deltas[0], deltas[1]))
    out.write('};\n')
    sys.stderr.write('ranges: %d, case ranges: %d\n' % (len(rows), len(cases)))


if __name__ == '__main__':
    main()
